/** @returns {string[]} כל שמות המקצועות שיש להם לפחות נושא אחד בקטלוג */
export function catalogSubjectNames() {
  return [...new Set(CURRICULUM_TOPICS.map((t) => t.subjectName))];
}

/**
 * @param {string} subjectName
 * @param {string} grade
 * @returns {import('../models/types.js').CurriculumTopic[]}
 */
export function topicsFor(subjectName, grade) {
  return CURRICULUM_TOPICS.filter((t) => t.subjectName === subjectName && t.grade === grade);
}

/**
 * התאמה מקומית פשוטה (לא AI, לא חיפוש) - מציעה שמות מקצוע מהקטלוג שדומים לשם שהמשתמשת הקלידה,
 * לתרחיש "לא נמצא מקצוע בשם X, התכוונת ל...?".
 * @param {string} customName
 * @returns {string[]} עד 3 הצעות
 */
export function suggestSimilarSubjects(customName) {
  const normalized = customName.trim().toLowerCase();
  if (!normalized) return [];
  return catalogSubjectNames()
    .filter((name) => {
      const n = name.toLowerCase();
      return n.includes(normalized) || normalized.includes(n);
    })
    .slice(0, 3);
}
